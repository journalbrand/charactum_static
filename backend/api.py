# Request/Response Models
class NodeCreate(BaseModel):
    name: str
    type: str
    description: str = ""

    @field_validator('type')
    @classmethod
    def type_must_be_in_ontology(cls, v: str) -> str:
        """Validate that the type string is a known node type in the ontology."""
        if v not in get_ontology().node_types:
            raise ValueError(f"Unknown node type: '{v}'. Must be one of {list(get_ontology().node_types)}")
        return v

class NodeUpdate(BaseModel):
    name: Optional[str] = None
    description: Optional[str] = None

class NodeResponse(BaseModel):
    """Response model for nodes using Neo4j IDs."""
    id: str  # Neo4j ID
    elementId: str  # Same as id
    name: str
    type: str
    description: str = ""

class RelationshipCreate(BaseModel):
    """Schema for creating a new relationship."""
    type: str
    source: str
    target: str
    properties: Optional[dict] = None

class RelationshipResponse(BaseModel):
    """Schema for relationship responses."""
    id: str
    type: str
    source: str
    target: str
    properties: Optional[dict] = None

# LLM Request/Response Models
