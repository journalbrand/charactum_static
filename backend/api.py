@app.post("/api/llm/generate", response_model=LLMGenerateResponse)
async def generate_nodes(request: LLMGenerateRequest):
    """Generate node candidates using LLM."""
    try:
        # --- Backend Guard-rail: Validate instruction against context and ontology --- 
        if request.context and request.context.get("node_type"): # Use .get() for safety
            context_node_type = request.context["node_type"]       # Use dictionary access
            instruction = request.instruction                 # instruction is a Pydantic model, attribute access is fine
            rel_type_str = instruction.relationship_type
            is_source_context = instruction.is_source

            rule = next((r for r in get_ontology().relationship_rules if r["name"] == rel_type_str), None)

            if not rule:
                raise HTTPException(status_code=400, detail=f"Invalid relationship type '{rel_type_str}' in instruction.")

            if is_source_context:
                if context_node_type not in rule["from"]:
                    raise HTTPException(
                        status_code=400, 
                        detail=f"Context node of type '{context_node_type}' cannot be the source for a '{rel_type_str}' relationship. "
                               f"Valid source types are: {rule['from']}. Instruction stated source type: '{instruction.source_type}'."
                    )
                if instruction.source_type != context_node_type:
                    raise HTTPException(
                        status_code=400,
                        detail=f"Instruction source_type '{instruction.source_type}' does not match context node type '{context_node_type}' when context is source."
                    )
            else: # Context node is TARGET
                if context_node_type not in rule["to"]:
                    raise HTTPException(
                        status_code=400, 
                        detail=f"Context node of type '{context_node_type}' cannot be the target for a '{rel_type_str}' relationship. "
                               f"Valid target types are: {rule['to']}. Instruction stated target type: '{instruction.target_type}'."
                    )
                if instruction.target_type != context_node_type:
                     raise HTTPException(
                        status_code=400,
                        detail=f"Instruction target_type '{instruction.target_type}' does not match context node type '{context_node_type}' when context is target."
                    )
        # --- End of Backend Guard-rail --- 

        logger.info("Step 3: API - Request received (passed guard-rails)", extra={
            "instruction": request.instruction.dict(),
            "context": json.dumps(request.context if request.context else {}, indent=2),
            "request_data": json.dumps(request.dict(), indent=2)
        })
        
        llm_service = LLMService()
        logger.info("Step 3: API - Calling LLM service")
        
        # request.context is already a dict or None here. Pass it directly.
        # request.instruction is a Pydantic model, .dict() is correct.
        candidates = await llm_service.generate_candidates(request.instruction.dict(), request.context)
        
        logger.info("Step 3: API - Received candidates from LLM service", extra={
            "candidates_count": len(candidates),
            "raw_candidates": json.dumps(candidates, indent=2)
        })
        
        response = LLMGenerateResponse(
            candidates=candidates,
            message="Successfully generated candidates"
        )
        
        logger.info("Step 3: API - Sending response", extra={
            "candidates_count": len(candidates),
            "candidates": json.dumps(candidates, indent=2),
            "full_response": json.dumps(response.dict(), indent=2),
            "response_model": str(type(response))
        })
        
        return response

    except ValueError as e: # Catches ValueErrors from LLMService, Pydantic model validation if any
        logger.error(f"ValueError in /api/llm/generate: {str(e)}", exc_info=True)
        raise HTTPException(status_code=400, detail=str(e))
    except HTTPException: # Re-raise HTTPExceptions explicitly raised by guard-rail or other logic
        raise
    except Exception as e: # Catch-all for unexpected errors
        logger.error(f"Unexpected error in /api/llm/generate: {str(e)}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Internal server error during candidate generation: {str(e)}")


@app.post("/api/llm/edit-description", response_model=NodeResponse)
async def llm_edit_description(request: LLMEditDescriptionRequest, db: OntorumDB = Depends(get_db)):
    """Use the LLM to edit a node's description and update it."""
    try:
        node = db.get_node(request.node_id)
        if not node:
            raise HTTPException(status_code=404, detail="Node not found")

        llm_service = LLMService()
        new_desc = await llm_service.edit_description(node, request.instruction)
        updated = db.update_node(request.node_id, node["name"], new_desc)
        return node_to_response(updated)
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error editing description with LLM: {e}")
        raise HTTPException(status_code=500, detail="Failed to edit description")

