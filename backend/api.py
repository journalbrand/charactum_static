@app.post("/api/relationships", response_model=RelationshipResponse)
def create_relationship(rel_data: RelationshipCreate, db: OntorumDB = Depends(get_db)):
    """Create a new relationship between nodes."""
    logger.info(f"API create_relationship: Received rel_data: {rel_data.model_dump_json(indent=2)}")
    
    source_node = db.get_node(rel_data.source)
    target_node = db.get_node(rel_data.target)
    
    logger.info(f"API create_relationship: Fetched source_node for ID {rel_data.source}: {json.dumps(source_node, indent=2) if source_node else 'Not found'}")
    logger.info(f"API create_relationship: Fetched target_node for ID {rel_data.target}: {json.dumps(target_node, indent=2) if target_node else 'Not found'}")

    if not source_node or not target_node:
        logger.error(f"API create_relationship: One or both nodes not found. Source ID: {rel_data.source}, Target ID: {rel_data.target}")
        raise HTTPException(status_code=404, detail="One or both nodes not found")

    try:
        source_type_str = source_node["type"].lower() # This is string e.g. "particular"
        target_type_str = target_node["type"].lower() # This is string e.g. "universal"
        rel_type_str = rel_data.type                 # This is string e.g. "INSTANCE_OF"
        
        # Convert rel_type_str to Enum member for GraphLinter
        try:
            rel_type_enum = get_ontology().RelationshipType(rel_type_str)
        except ValueError:
             raise HTTPException(status_code=400, detail=f"Invalid relationship type string: '{rel_type_str}'")

        is_valid, error_msg = GraphLinter.validate_relationship(
            from_type=source_type_str, # Expected as string
            to_type=target_type_str,   # Expected as string
            rel_type=rel_type_enum     # Expected as Enum member
        )
        if not is_valid:
            raise HTTPException(status_code=400, detail=error_msg)
    except HTTPException: # Re-raise specific HTTP exceptions
        raise
    except Exception as e: # Catch other potential errors during validation
        logger.error(f"Error validating relationship: {str(e)}")
        raise HTTPException(status_code=400, detail=f"Error validating relationship: {str(e)}")

    relationship_to_create = {
        'type': rel_data.type, # Use the original string for DB creation
        'source': source_node['id'],
        'target': target_node['id'],
        'properties': rel_data.properties
    }
    logger.info(f"API create_relationship: Attempting to create relationship: {json.dumps(relationship_to_create, indent=2)}")

    try:
        result = db.create_relationship(relationship_to_create)
        logger.info(f"API create_relationship: Successfully created relationship: {json.dumps(result, indent=2)}")
        return RelationshipResponse(**result)
    except Exception as e:
        logger.error(f"Error creating relationship in DB: {str(e)}")
        raise HTTPException(status_code=500, detail=str(e))

