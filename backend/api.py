@app.get("/api/schema/node-types")
async def get_node_types():
    """Get all available node types with their metadata."""
    types_response = []
    current_ontology = get_ontology()
    for type_key in current_ontology.node_types:
        metadata = current_ontology.node_metadata.get(type_key, {})
        types_response.append({
            "value": type_key,
            "label": metadata.get("label", type_key.capitalize()),
            "metadata": metadata
        })
    return {"types": types_response}

@app.get("/api/schema/relationship-types")
async def get_relationship_types():
    """Get all available relationship types."""
    types_response = []
    current_ontology = get_ontology()
    for rel_type_enum in current_ontology.RelationshipType:
        types_response.append({
            "value": rel_type_enum.value,
            "label": rel_type_enum.value.replace('_', ' ').capitalize()
        })
    return {"types": types_response}

@app.get("/api/schema/allowed-relationship-schemas")
async def get_allowed_relationship_schemas():
    """Get all allowed relationship combinations, including properties from the ontology spec."""
    allowed_schemas_api = []
    current_ontology = get_ontology()
    linter_schemas = GraphLinter.get_allowed_relationship_schemas()

    rules_properties_map = {rule["name"]: rule.get("properties", []) for rule in current_ontology.relationship_rules}

    for schema in linter_schemas:
        allowed_schemas_api.append({
            "from_type": schema.from_type.value,
            "to_type": schema.to_type.value,
            "relationship_type": schema.relationship_type.value,
            "properties": rules_properties_map.get(schema.relationship_type.value, [])
        })
    return {"relationships": allowed_schemas_api}

